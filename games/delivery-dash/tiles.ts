export type Dir = 0 | 1 | 2 | 3; // N E S W
const LETTER = 'NESW';

/** The open sides of a catalogue tile as a 4-bit mask (bit d = side d). */
export function tileMask(id: number): number {
  const row = CATALOGUE[id];
  let m = 0;
  for (const ch of row[3]) { const d = LETTER.indexOf(ch); if (d >= 0) m |= 1 << d; }
  return m;
}

/** A side after k quarter turns (three.js rotation.y = k·π/2 turns E → N → W → S). */
export const turnDir = (d: number, k: number): number => ((d - k) % 4 + 4) % 4;

export function turnMask(m: number, k: number): number {
  let out = 0;
  for (let d = 0; d < 4; d++) if (m & (1 << d)) out |= 1 << turnDir(d, k);
  return out;
}

/** The quarter turns that give a tile the wanted open sides (or -1). */
export function fitTurns(id: number, want: number): number {
  const m = tileMask(id);
  for (let k = 0; k < 4; k++) if (turnMask(m, k) === want) return k;
  return -1;
}

/** Quarter turns that bring side `from` of a tile to side `to`. */
export const turnsFor = (from: number, to: number): number => ((from - to) % 4 + 4) % 4;
