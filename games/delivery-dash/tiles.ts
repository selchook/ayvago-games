// Delivery Dash: the catalogue of Kenney's "3D Road Tiles" (Road Pack 1.0, kenney/road-pack).
//
// The pack's 294 tiles are only numbered (tile000 … tile293), so every tile was classified from
// its geometry: each GLB was rendered top-down and in an oblique view into contact sheets, and a
// script read the materials along each of the four edges (asphalt, pavement, grass, water …) and
// the asphalt heights. The edge signature says what a tile connects to:
//   city    pavement 0.25 | asphalt 0.5 | pavement 0.25 (two-lane road with sidewalks)
//   green   grass | narrow sidewalk | asphalt 0.5 | sidewalk | grass (suburban road with verges)
//   narrow  the city road cut out without its outer edge (a loose piece, for viaducts)
//   lane    a one-lane road (asphalt 0.25)
//   irregular  curves and offsets that meet the edge off-centre
// Columns: id, kind, shape (road shape, or block for tiles without asphalt), open sides in the
// tile's own orientation (N = -z, E = +x, S = +z, W = -x), road family, level:
//   flat (road surface 0.2 above the base), slope (0.2 → 0.567 across the tile), hump (bridge
//   deck 0.315 in the middle), raised (deck at 0.567), mid (0.36–0.41), cut (sunk between walls).
