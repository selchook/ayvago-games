/** "1st", "2nd" … in English; "1." in Turkish. */
export function ordinal(n: number): string {
  if (getLang() === 'tr') return `${n}.`;
  return n + (n === 1 ? 'st' : n === 2 ? 'nd' : n === 3 ? 'rd' : 'th');
}

/** A decimal number in the current language (Turkish writes a comma). */
export function num(v: number, digits: number): string {
  const s = v.toFixed(digits);
  return getLang() === 'tr' ? s.replace('.', ',') : s;
}

export const secs = (v: number): string => t('seconds', { s: num(v, 2) });
export const metres = (v: number): string => t('metres', { m: num(v, 2) });
