#!/usr/bin/env node
// Bundles the platform adapter (src/core/ayvago/adapter.ts, vendored verbatim from the platform)
// as plain JS for the Unity WebGL template:
//   unity/com.ayvago.sdk/WebGLTemplates~/Ayvago/TemplateData/ayvago-adapter.js
// The page then calls window.AyvagoAdapter.createPlatformAdapter({ gameId }).
// Usage: node scripts/build-unity-adapter.mjs           (writes the file)
//        node scripts/build-unity-adapter.mjs --check   (fails when the committed file is stale)
// Unity preprocesses the .js files of a WebGL template ({{{ VAR }}} and #if lines), so the bundle
// must contain neither; the script checks that too.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src', 'core', 'ayvago', 'adapter.ts');
export const ADAPTER_JS = join(root, 'unity', 'com.ayvago.sdk', 'WebGLTemplates~', 'Ayvago', 'TemplateData', 'ayvago-adapter.js');

export async function bundleAdapter() {
  const version = (readFileSync(src, 'utf8').match(/ADAPTER_VERSION = '([^']+)'/) || [])[1] ?? '?';
  const out = await build({
    entryPoints: [src],
    bundle: true,
    format: 'iife',
    globalName: 'AyvagoAdapter',
    target: 'es2017',
    write: false,
    legalComments: 'none',
    logLevel: 'silent',
  });
  const header =
    `// GENERATED by scripts/build-unity-adapter.mjs from src/core/ayvago/adapter.ts (adapter ${version}).\n` +
    '// Do not edit: change the adapter in the platform repo (packages/platform-adapter), vendor it into\n' +
    '// the studio, then run `node scripts/build-unity-adapter.mjs`.\n';
  const js = header + out.outputFiles[0].text;
  if (js.includes('{{{') || /^#/m.test(js)) throw new Error('the bundle contains Unity template syntax ({{{ or a line starting with #)');
  return js;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const js = await bundleAdapter();
  const rel = relative(root, ADAPTER_JS);
  if (process.argv.includes('--check')) {
    const current = existsSync(ADAPTER_JS) ? readFileSync(ADAPTER_JS, 'utf8') : '';
    if (current !== js) {
      console.error(`${rel} is stale: run node scripts/build-unity-adapter.mjs and commit the result.`);
      process.exit(1);
    }
    console.log(`${rel} is up to date.`);
  } else {
    writeFileSync(ADAPTER_JS, js);
    console.log(`wrote ${rel} (${Math.round(js.length / 1024)} KB)`);
  }
}
